# Type Casting in Python

# Type Casting means converting one data type into another.

# 1. String to Integer
age = "18"
age = int(age)

print("String to Integer:")
print(age)
print(type(age))


# 2. String to Float
price = "99.99"
price = float(price)

print("\nString to Float:")
print(price)
print(type(price))


# 3. Integer to Float
number = 10
number = float(number)

print("\nInteger to Float:")
print(number)
print(type(number))


# 4. Float to Integer
decimal = 10.75
decimal = int(decimal)

print("\nFloat to Integer:")
print(decimal)
print(type(decimal))


# 5. Integer to String
score = 90
score = str(score)

print("\nInteger to String:")
print(score)
print(type(score))


# 6. Float to String
rating = 8.5
rating = str(rating)

print("\nFloat to String:")
print(rating)
print(type(rating))


# 7. String to Boolean
value = "Hello"
value = bool(value)

print("\nString to Boolean:")
print(value)
print(type(value))


# 8. Integer to Boolean
number = 1
number = bool(number)

print("\nInteger to Boolean:")
print(number)
print(type(number))


# 9. Boolean to Integer
is_active = True
is_active = int(is_active)

print("\nBoolean to Integer:")
print(is_active)
print(type(is_active))


# 10. Boolean to String
status = True
status = str(status)

print("\nBoolean to String:")
print(status)
print(type(status))