"""
 Variables in Python

Variables are used to store data.
Python automatically determines the data type based on the value assigned.
"""

# String
player_name = "Lamine Yamal"

# Integer
age = 18

# Float
market_value = 200.5  # in million euros

# Boolean
is_starting_player = True

print("Player Name:", player_name)
print("Age:", age)
print("Market Value (€M):", market_value)
print("Starting Player:", is_starting_player)
